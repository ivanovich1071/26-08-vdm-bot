"""Нормализация русского текста для поиска.

Полноценная морфология тут избыточна: запросы короткие («мячи для зала», «столы
регулируемые»), а каталог узкий. Хватает отсечения окончаний — оно склеивает
«мячи/мяч/мячей» и «столы/стол/столов», не притягивая посторонние слова.
"""

from __future__ import annotations

import re

_TOKEN = re.compile(r"[a-zа-яё0-9]+", re.IGNORECASE)
_MIN_STEM = 3

# Порядок важен: длинные окончания проверяются раньше коротких.
_SUFFIXES = (
    "иями", "ями", "ами", "иях", "ыми", "ими", "ому", "ему", "ого", "его",
    "ых", "их", "ях", "ах", "ов", "ев", "ий", "ый", "ой", "ая", "яя", "ое", "ее", "ые", "ие",
    # «ия» рядом с «ии» не для полноты: без неё «классификация» и «классификации»
    # сводились к разным основам и переставали совпадать.
    "ом", "ем", "ам", "ям", "ую", "юю", "ей", "ии", "ия", "ию",
    "ь", "я", "ю", "у", "е", "о", "и", "ы", "а", "й",
)


def tokenize(text: str) -> list[str]:
    return _TOKEN.findall(text.lower().replace("ё", "е"))


# Беглая гласная: «станок» и «станки» отсекаются в «станок» и «станк» и перестают
# совпадать. Из-за этого запрос «станки для школьных мастерских» выдавал
# музыкальную шкатулку, а настоящие станки оставались внизу. Правило применяется
# и к запросу, и к каталогу, поэтому важно не то, насколько оно верно
# лингвистически, а то, что обе стороны сводятся к одному виду.
_FLEETING = (("ок", "к"), ("ек", "к"), ("ец", "ц"))

# Слова, которые человек и каталог называют по-разному. Раскрывается только
# запрос: трогать индекс значило бы размывать и без того короткие названия.
# Список намеренно короткий — каждая пара взята из живого запроса заказчика.
_SYNONYMS: dict[str, tuple[str, ...]] = {
    "спортзал": ("спортивн", "зал", "физкультурн"),
    "физзал": ("спортивн", "зал", "физкультурн"),
    "физкультурн": ("спортивн",),
    "спортивн": ("физкультурн",),
    "мастерск": ("труд", "технолог"),
    "садик": ("сад", "дошкольн"),
    "детсад": ("сад", "дошкольн"),
    "доу": ("сад", "дошкольн"),
    "логопед": ("логопедическ", "реч"),
    "логопедическ": ("логопед",),
    "дефектолог": ("коррекционн",),
}


def stem(token: str) -> str:
    """Отсечение окончания. Латиница и артикулы вроде `min95030` не трогаются."""
    if len(token) <= _MIN_STEM or not token[0].isalpha() or token.isascii():
        return token
    for suffix in _SUFFIXES:
        if token.endswith(suffix) and len(token) - len(suffix) >= _MIN_STEM:
            token = token[: -len(suffix)]
            break
    for ending, replacement in _FLEETING:
        if token.endswith(ending) and len(token) > _MIN_STEM + 1:
            return token[: -len(ending)] + replacement
    return token


def stems(text: str) -> list[str]:
    return [stem(token) for token in tokenize(text)]


def expand(tokens: list[str]) -> list[str]:
    """Слова запроса плюс их синонимы, без повторов и с сохранением порядка."""
    result: list[str] = []
    for token in tokens:
        for word in (token, *_SYNONYMS.get(token, ())):
            if word not in result:
                result.append(word)
    return result


def trigrams(text: str) -> set[str]:
    """Триграммы для устойчивости к опечаткам и слитному написанию."""
    padded = f"  {text.lower().replace('ё', 'е')} "
    return {padded[i : i + 3] for i in range(len(padded) - 2)}
