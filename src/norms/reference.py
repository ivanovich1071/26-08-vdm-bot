# Вопрос об обязанности — «по чему обязан укомплектовать садик», «на основании
# чего». Отвечать на него надо справкой, даже если рядом стоят слова про
# комплектование: человек спрашивает про основание, а не просит подобрать товар.
_ASKING_ABOUT_DUTY = re.compile(
    r"\bобязан\w*|\bна\s+основании\s+чего|\bпо\s+чему\b|\bчем\s+регулир\w+|"
    r"\bчто\s+требует\w*|\bтребовани\w+\s+(?:как\w+|чег\w+)|\bкого\s+касается\b|"
    r"\bдолжен\s+ли\b|\bдолжна\s+ли\b|\bнужно\s+ли\s+по\b",
    re.IGNORECASE,
)
# Вопрос о самом документе. Разница существенная: «что значит приказ 838» — это
# справка, «что нужно в кабинет физики по приказу 838» — это подбор, и отвечать
# на него справкой было бы издевательством.
_ASKING_ABOUT_DOC = re.compile(
    r"что\s+(?:это\s+)?(?:такое|значит|за)\b|\bзначит\b|расскажи\w*\s+(?:про|о|об)\b|"
    r"\bпояснит?\w*|\bобъясни\w*|\bзачем\s+(?:нужен|нужна|нужно)\b|\bв\s+чём\s+смысл",
    re.IGNORECASE,
)
# Признаки товарного запроса: даже при упоминании документа это подбор, а не справка.
_ASKING_FOR_GOODS = re.compile(
    r"\bподбер\w+|\bпокаж\w+|\bнайд\w+|\bкупи\w+|\bзакаж\w+|\bцен\w+|\bстоит\b|"
    r"\bоснаст\w+|\bукомплектова\w+|\bоборудован\w+\s+для\b|\bчто\s+входит\b|"
    r"\bкорзин\w+|\bв\s+наличии\b|\bчто\s+нужно\s+в\b",
    re.IGNORECASE,
)


def question_about_document(text: str) -> str | None:
    """Идентификатор документа, если пользователь спрашивает именно о документе.

    Возвращает None для товарного запроса — там нужен подбор, а не справка.
    """
    if not text:
        return None
    found = document_ids_in_text(text) or _bare_number(text)
    if not found:
        return None
    # Вопрос об основании перевешивает товарные слова: «по чему обязан
    # укомплектовать садик по приказу 1057» — это про приказ, а не про товары.
    if _ASKING_ABOUT_DUTY.search(text):
        return found[0]
    if _ASKING_FOR_GOODS.search(text):
        return None
    stripped = _without_document(text)
    # Голое упоминание — «приказ 838», «1057?» — это тоже вопрос о документе:
    # человек не знает, что спросить, и ждёт объяснения.
    if _ASKING_ABOUT_DOC.search(text) or len(stripped.split()) <= 2:
        return found[0]
    return None


def explain(doc_id: str, coverage: dict[str, int] | None = None) -> str:
    """Справка по документу. `coverage` — что по нему есть в каталоге."""
    reference = REFERENCES.get(doc_id)
    document = docs.DOCUMENTS.get(doc_id)
    if reference is None or document is None:
        return ""

    lines = [document.full_name or document.short_name, "", reference.summary]
    lines += ["", f"Кого касается: {reference.audience}."]
    if reference.numbering:
        lines += ["", reference.numbering]

    if coverage and coverage.get("products"):
        products = coverage["products"]
        codes = coverage.get("codes", 0)
        tail = f", из них по {coverage['with_code']} известен пункт перечня" if codes else ""
        lines += ["", f"В каталоге к документу привязано позиций: {products}{tail}."]
        if codes:
            # Всего пунктов в приказе — обязательно рядом с закрытыми. Пока
            # называлось только «разных пунктов — 892», модель повторяла это как
            # «в нём 892 пункта», и покрытие выглядело втрое выше настоящего:
            # в приказе 1057 пунктов две с половиной тысячи.
            total = coverage.get("total_items") or 0
            closed = f"; закрыто пунктов перечня — {codes}"
            closed += f" из {total}." if total else "."
            lines[-1] = lines[-1][:-1] + closed

    if reference.actions:
        lines += ["", "Что могу сделать прямо сейчас:"]
        lines += [f"• {action}" for action in reference.actions]

    lines += ["", DISCLAIMER]
    return "\n".join(lines)


def coverage(index, doc_id: str, total_items: int = 0) -> dict[str, int]:  # noqa: ANN001
    """Сколько позиций каталога привязано к документу. Считается по базе знаний.

    Цифра в ответе не должна устаревать вместе с текстом справки: выгрузка
    меняется, и «2 092 позиции» верно ровно до следующей загрузки прайса.
    """
    products = with_code = 0
    codes: set[str] = set()
    for product in index.products:
        matched = [ref for ref in product.norms if ref.doc_id == doc_id]
        if not matched:
            continue
        products += 1
        with_item = [ref.item_code for ref in matched if ref.item_code]
        if with_item:
            with_code += 1
            codes.update(with_item)
    return {
        "products": products,
        "with_code": with_code,
        "codes": len(codes),
        # Всего пунктов в самом приказе — из разобранного текста документа.
        # Ноль означает «текст приказа не загружен», и тогда справка про полноту
        # молчит, а не врёт.
        "total_items": total_items,
    }


