"""Справка по нормативным документам — ответ на «что значит приказ 838».

Отдельный модуль, а не строка в промпте, по трём причинам.

**Ответ не должен зависеть от модели.** Провайдер бывает недоступен, и как раз
на нормативном вопросе это заметнее всего: пользователь спрашивает про закон, а
получает список товаров. Справка отдаётся напрямую, без обращения к модели.

**Формулировки должны быть проверяемыми.** Всё, что тут написано, взято из данных
заказчика: названия документов — из описаний выгрузки и разделов каталога, охват —
подсчитан по собранной базе знаний прямо в момент ответа. Ничего не пересказывается
по памяти модели.

**Об обязанностях говорим осторожно.** Бот не юрист: он сообщает, что перечень
утверждён приказом и какие позиции каталога к нему привязаны, но не утверждает,
что учреждение обязано купить именно это. Спорное уходит менеджеру и методисту.
Список утверждений, требующих подтверждения заказчиком, — в отдельном файле
НОРМАТИВКА_НА_ПОДТВЕРЖДЕНИЕ.md.
"""

