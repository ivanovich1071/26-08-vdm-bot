_BARE_NUMBER = re.compile(r"\b(838|1057)\b")


def _bare_number(text: str) -> list[str]:
    """Номер приказа без слова «приказ»: «обязан ли садик закупать по 1057».

    Правило работает только внутри распознавания вопроса о документе. В общем
    разборе текста оно опасно — там же ищутся номера пунктов и суммы.
    """
    if not (_ASKING_ABOUT_DUTY.search(text) or _ASKING_ABOUT_DOC.search(text)):
        return []
    match = _BARE_NUMBER.search(text)
    if match is None:
        return []
    return [docs.ORDER_838.id if match.group(1) == "838" else docs.ORDER_1057.id]


def _without_document(text: str) -> str:
    """Текст без упоминания документа — чтобы понять, осталось ли в нём что-то ещё."""
    cleaned = re.sub(
        r"приказ\w*|\bот\s*\d{2}\.\d{2}\.\d{4}|№|\bn\b|\b838\b|\b1057\b|фгос\s*до|фоп\s*до|"
        r"\bчто\b|\bэто\b|\bтакое\b|\bзначит\b|\bза\b|\bи\b|\bили\b|\bдругие\b|"
        r"нормативк\w*|\bзакон\w*",
        " ",
        text,
        flags=re.IGNORECASE,
    )
    return re.sub(r"[^\w\s]", " ", cleaned).strip()
